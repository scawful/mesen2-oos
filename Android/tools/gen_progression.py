#!/usr/bin/env python3
"""Generate ProgressionData.java from Oracle's Data/debug/checkpoints.json + warps.json.

The Android Progression page applies the same checkpoints as the desktop
oracle_cheats tool. This script resolves each checkpoint's 'after' chain
(oldest first) and each location's warp plan at build time, so the app needs no
JSON parser and host tests can check the table directly.

Usage: gen_progression.py <oracle-repo> <out ProgressionData.java>
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path


def hexint(v) -> int:
    if isinstance(v, int):
        return v
    s = str(v).strip().lower().replace("$", "0x")
    return int(s, 16) if s.startswith("0x") else int(s, 16)


def jstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def resolve(by_id: dict, cp_id: str) -> list[dict]:
    chain, seen, cur = [], set(), by_id[cp_id]
    while cur is not None:
        if cur["id"] in seen:
            raise SystemExit(f"checkpoint chain loops at {cur['id']}")
        seen.add(cur["id"])
        chain.append(cur)
        parent = cur.get("after")
        cur = by_id.get(parent) if parent else None
        if parent and cur is None:
            raise SystemExit(f"{chain[-1]['id']} is after unknown {parent}")
    chain.reverse()
    return chain


def write_op(w: dict) -> tuple[int, int, int]:
    """(addr, op, operand): op 0 = value, 1 = set_bits, 2 = clear_bits."""
    addr = hexint(w["addr"])
    # Most writes are in the $7EF000 save block; a few reset live WRAM (LinkState $7E005D).
    if not 0x7E0000 <= addr <= 0x7FFFFF:
        raise SystemExit(f"write {w['addr']} is outside WRAM")
    for op, key in enumerate(("value", "set_bits", "clear_bits")):
        if key in w:
            return addr, op, hexint(w[key]) & 0xFF
    raise SystemExit(f"write {w['addr']} has no value/set_bits/clear_bits")


def main() -> None:
    repo, out = Path(sys.argv[1]), Path(sys.argv[2])
    cp_path = repo / "Data/debug/checkpoints.json"
    warps_path = repo / "Data/debug/warps.json"
    cps = json.loads(cp_path.read_text())
    warps = json.loads(warps_path.read_text())
    entrances = warps["entrances"]
    areas = {hexint(a["area"]): a for a in warps["areas"]}

    def entrance(eid: int) -> dict:
        for e in entrances:
            if hexint(e["id"]) == eid:
                return e
        return {"id": f"0x{eid:02X}"}

    def prime(area: dict) -> int:
        via = hexint(area["via_room"])
        for e in entrances:
            if e.get("room") and hexint(e["room"]) == via:
                return hexint(e["id"])
        for e in entrances:
            if e.get("area") and hexint(e["area"]) == hexint(area["area"]) and e.get("exit") == "table":
                return hexint(e["id"])
        return 0x76 if hexint(area["area"]) & 0x40 else 0x01

    def cache_area(e: dict) -> dict:
        if e.get("area") is not None and hexint(e["area"]) in areas:
            return areas[hexint(e["area"])]
        abyss = e.get("area") is not None and hexint(e["area"]) & 0x40
        return areas[0x40 if abyss else 0x33]

    by_id = {c["id"]: c for c in cps["checkpoints"]}
    rows = []
    for c in cps["checkpoints"]:
        chain = resolve(by_id, c["id"])
        writes = [write_op(w) for link in chain for w in link.get("writes", [])]
        loc = c["location"]
        exp = c.get("expect", {})
        mods = [hexint(m) for m in exp.get("modules", [])]
        if "entrance" in loc:
            eid = hexint(loc["entrance"])
            e = entrance(eid)
            kind = "ENTRANCE"
            target = eid
            cache = e.get("exit") == "cache"
            ca = cache_area(e) if cache else None
            area = hexint(ca["area"]) if ca else -1
            via = hexint(ca["via_room"]) if ca else -1
            prime_id = -1
            room = hexint(e["room"]) if e.get("room") else -1
        else:
            a = areas[hexint(loc["area"])]
            kind = "AREA"
            target = hexint(a["area"])
            cache = False
            area = target
            via = hexint(a["via_room"])
            prime_id = prime(a)
            room = -1
        exp_room = hexint(exp["room"]) if "room" in exp else -1
        exp_area = hexint(exp["area"]) if "area" in exp else -1
        rows.append((c, chain, writes, kind, target, cache, area, via, prime_id, room, mods, exp_room, exp_area))

    tested = cps.get("rom_tested", "?")
    if isinstance(tested, dict):
        tested = Path(str(tested.get("path", "?"))).name
    digest = hashlib.sha256(cp_path.read_bytes() + warps_path.read_bytes()).hexdigest()[:12]
    lines = [
        "package ca.mesen.oos;",
        "",
        "// GENERATED by Android/tools/gen_progression.py from Oracle Data/debug/",
        "// checkpoints.json + warps.json (rom_tested %s, sha %s)." % (tested, digest),
        "// Do not edit by hand; rerun the generator.",
        "final class ProgressionData {",
        "    private ProgressionData() {}",
        "",
        "    static final String SOURCE = " + jstr("checkpoints %s %s" % (tested, digest)) + ";",
        "",
        "    static final Progression.Checkpoint[] CHECKPOINTS = {",
    ]
    for (c, chain, writes, kind, target, cache, area, via, prime_id, room, mods, exp_room, exp_area) in rows:
        w = ", ".join(f"0x{a:06X}, {op}, 0x{v:02X}" for a, op, v in writes)
        m = ", ".join(f"0x{x:02X}" for x in mods)
        ch = ", ".join(jstr(x["id"]) for x in chain)
        lines += [
            "        new Progression.Checkpoint(",
            f"            {jstr(c['id'])}, {jstr(c['label'])}, {int(c.get('beat', 0))},",
            f"            Progression.Kind.{kind}, 0x{target:02X}, {str(cache).lower()},",
            f"            {area}, {via}, {prime_id}, {room},",
            f"            new int[]{{{m}}}, {exp_room}, {exp_area},",
            f"            new String[]{{{ch}}},",
            f"            new int[]{{{w}}}),",
        ]
    lines += ["    };", "}", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(rows)} checkpoints, sha {digest})")


if __name__ == "__main__":
    main()
